export function getModuleByCode(code: ModuleCode | string): CatalogueModule | undefined {
  return BY_CODE.get(code as ModuleCode);
}

export function getModulesByDomaine(domaineId: CatalogueModule['domaineId']): CatalogueModule[] {
  return MODULES_CATALOGUE_2027.filter((m) => m.domaineId === domaineId);
}

export function getModulesDisponibles(): CatalogueModule[] {
  return MODULES_CATALOGUE_2027.filter((m) => m.disponibilite === 'disponible');
}

export function assertCatalogueModulesIntegrity(): {
  ok: boolean;
  errors: string[];
  counts: { modules: number; domaines: number; disponibles: number; ouverture2027: number };
} {
  const errors: string[] = [];
  const codes = MODULES_CATALOGUE_2027.map((m) => m.code);
  if (new Set(codes).size !== codes.length) errors.push('Codes modules en double');
  if (MODULES_CATALOGUE_2027.length !== 35) {
    errors.push(`Attendu 35 modules, trouvé ${MODULES_CATALOGUE_2027.length}`);
  }
  const disponibles = MODULES_CATALOGUE_2027.filter((m) => m.disponibilite === 'disponible');
  const ouverture = MODULES_CATALOGUE_2027.filter((m) => m.disponibilite === 'ouverture-2027');
  if (disponibles.length !== 6) errors.push(`Attendu 6 disponibles, trouvé ${disponibles.length}`);
  if (ouverture.length !== 29) errors.push(`Attendu 29 en 2027, trouvé ${ouverture.length}`);
  const only4h = MODULES_CATALOGUE_2027.filter((m) => m.dureeHeures === 4);
  if (only4h.length !== 1 || only4h[0]?.code !== 'NUM-01') {
    errors.push('Seul NUM-01 doit durer 4 h');
  }
  const domaines = new Set(MODULES_CATALOGUE_2027.map((m) => m.domaineId));
  if (domaines.size !== 7) errors.push(`Attendu 7 domaines, trouvé ${domaines.size}`);
  return {
    ok: errors.length === 0,
    errors,
    counts: {
      modules: MODULES_CATALOGUE_2027.length,
      domaines: domaines.size,
      disponibles: disponibles.length,
      ouverture2027: ouverture.length,
    },
  };
}
